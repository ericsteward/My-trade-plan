const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const app=fs.readFileSync('app.js','utf8');
const overview=fs.readFileSync('auto-fx-overview.js','utf8');
const fixture={};
const table={innerHTML:'',querySelectorAll:()=>[]};
const pairNames=['AUDCAD','EURCHF','AUDCHF','NZDUSD','AUDNZD','EURGBP','AUDJPY','EURCAD','EURJPY','GBPAUD','GBPCAD','GBPCHF','GBPJPY','NZDCAD','NZDCHF','NZDJPY','CADCHF','CADJPY','EURNZD','EURAUD','AUDUSD','EURUSD','GBPUSD','USDCHF','USDCAD','USDJPY','GBPNZD'];
const pairs=Object.fromEntries(pairNames.map(p=>[p,'WATCH']));
Object.assign(pairs,{AUDCAD:'BUY',EURCHF:'BUY',AUDCHF:'BUY',NZDUSD:'SELL'});
const ctx={pairs,db:{pairs:{}},document:{getElementById:id=>id==='pairBoard'?table:null},localStorage:{getItem:()=>JSON.stringify(fixture)}};
vm.createContext(ctx);
vm.runInContext(app.slice(app.indexOf('// Trading Mood describes'),app.indexOf('function openBoardPair')),ctx);
const mood=(data,plan,error)=>ctx.tradingMoodEvidence(data,plan,error);
assert.equal(mood(null).label,'MIXED/UNCONFIRMED');
assert.match(mood(null).reason,/Current D1 price evidence unavailable/);
const sell={date:'2026-10-30',close:1,refs:[null,2,2,2,2,2]};
const buyMixed={date:'2026-10-30',close:2,refs:[null,1,1,1,1,3]};
assert.match(mood(sell,'BUY').reason,/5\/6.*Y missing/);
assert.match(mood(sell,'BUY').reason,/Plan BUY conflicts with SELL bias/);
assert.match(mood(sell,'BUY').action,/resolve/);
assert.match(mood(buyMixed,'WATCH').reason,/4 above, 1 below/);
assert.equal(mood(buyMixed,'WATCH').label,'MIXED/UNCONFIRMED');
assert.match(mood(sell,'BUY',true).reason,/saved data may be stale/);
const allAligned={close:2,refs:[1,1,1,1,1,1]};
assert.equal(mood(allAligned,'BUY').label,'MIXED/UNCONFIRMED');
assert.doesNotMatch(mood(allAligned,'BUY').reason,/missing/);
assert.match(mood(allAligned,'BUY').reason,/momentum.*targets\/PTR unverified/);
ctx.renderPairBoard();
assert.equal((table.innerHTML.match(/<tbody>([\s\S]*?)<\/tbody>/)[1].match(/<tr>/g)||[]).length,27);
assert.equal((table.innerHTML.match(/<td style="font-weight:bold;color:#f7d88a">MIXED\/UNCONFIRMED/g)||[]).length,27);
fixture.AUDCAD={data:sell};
fixture.AUDNZD={data:buyMixed};
ctx.renderPairBoard();
assert.match(table.innerHTML,/SELL \(plan BUY\)/);
assert.match(table.innerHTML,/Plan BUY conflicts with SELL bias/);
assert.match(table.innerHTML,/BUY<\/td><td[^>]*>MIXED\/UNCONFIRMED/);
assert.match(table.innerHTML,/PROVIDER D1 2026-10-30/);
ctx.db.pairs.EURCHF={price:'2',yearly:'1',quarterly:'1',monthly:'1',weekly:'1',daily:'1',ema:'1',high:'3',low:'1',confirm:'yes',pattern:'inside'};
ctx.renderPairBoard();
assert.match(table.innerHTML,/<td>REVIEW<\/td>/);
assert.equal(ctx.db.pairs.EURCHF.price,'2');
assert.ok(overview.includes("tradingMoodEvidence(d,biases[p],Boolean(record?.error))"));
assert.ok(overview.includes('<th>Mood evidence / Plan action</th>'));
const direction=overview.match(/function direction\(d\)\{.*\}/)[0];
vm.runInContext(direction,ctx);
assert.equal(ctx.direction(buyMixed),'BUY BIAS — WAIT');
assert.equal(ctx.direction(sell),'SELL BIAS');
assert.ok(fs.readFileSync('index.html','utf8').includes('app.js?v=20-20261029-mood'));
assert.ok(fs.readFileSync('sw.js','utf8').includes("CACHE='greg-plan-20-mood'"));
console.log('PASS: 27-pair moods; missing and conflicting evidence; plan conflict; manual checks preserved; Buy/Sell logic preserved; cache version updated.');

